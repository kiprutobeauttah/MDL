def create_icon(name: str, color: str = "#FFFFFF", size: int = 20) -> QIcon:
    """Create QIcon from Feather icon name.
    
    Args:
        name: Icon name from FEATHER_ICONS
        color: Icon color (hex)
        size: Icon size in pixels
        
    Returns:
        QIcon instance
    """
    if name not in FEATHER_ICONS:
        # Return empty icon if not found
        return QIcon()
    
    # Get SVG and replace currentColor with specified color
    svg_data = FEATHER_ICONS[name].replace('stroke="currentColor"', f'stroke="{color}"')
    
    # Create SVG renderer
    renderer = QSvgRenderer(QByteArray(svg_data.encode()))
    
    # Create pixmap
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.transparent)
    
    # Render SVG to pixmap
    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()
    
    return QIcon(pixmap)


def get_icon_svg(name: str, color: str = "currentColor") -> str:
    """Get icon SVG string with color replacement.
    
    Args:
        name: Icon name
        color: Color to replace currentColor with
        
    Returns:
        SVG string
    """
    if name not in FEATHER_ICONS:
        return ""
    
    return FEATHER_ICONS[name].replace('stroke="currentColor"', f'stroke="{color}"')
